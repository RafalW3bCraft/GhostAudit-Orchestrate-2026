"""Evaluation workflow: official samples (if present) + hand-built synthetic cases -> report."""
from __future__ import annotations

import csv
import json
import os
import tempfile

from ghostaudit.agent import Agent
from ghostaudit.common import read_csv
from ghostaudit.schema import validate

from .metrics import score
from .synthetic import build


def _fmt(m):
    fa = ", ".join(f"{k}={v:.3f}" for k, v in m["field_accuracy"].items())
    return (f"- Cases: {m['cases']}\n- Case-level status accuracy: {m['status_accuracy']:.3f}\n"
            f"- Step-level precision / recall / F1: {m['step_precision']:.3f} / {m['step_recall']:.3f} / {m['step_f1']:.3f}\n"
            f"- Field-level accuracy on matched steps ({m['matched_step_keys']}): {fa}\n"
            f"- Sequence accuracy (exact array equality incl. status): {m['sequence_accuracy_exact']:.3f}\n"
            f"- Sequence similarity (LCS Dice): {m['sequence_similarity_lcs']:.3f}")


def run_all(dataset, config, use_llm, out_dir):
    sections, summary = [], {}
    sample_req = os.path.join(dataset, "sample_deletion_requests.csv")
    sample_gold = os.path.join(dataset, "sample_output.csv")
    if os.path.exists(sample_req) and os.path.exists(sample_gold):
        ag = Agent(dataset, config, use_llm)
        pred = ag.run(read_csv(sample_req))
        m = score(pred, read_csv(sample_gold))
        summary["official_sample"] = {k: v for k, v in m.items() if k != "failures"}
        sections.append("## Official sample set (`sample_output.csv`)\n\n" + _fmt(m))
        if m["failures"]:
            sections.append("### Sample failures (first 15)\n\n```json\n" + json.dumps(m["failures"][:15], indent=1) + "\n```")
        sections.append(f"Warnings: {len(ag.warnings)}; schema/validation errors: {len(ag.errors)}")
        for pr in pred:
            e = validate(pr["deletion_status"], json.loads(pr["steps_json"]))
            if e:
                sections.append(f"- schema violation {pr['case_id']}: {e}")
    else:
        sections.append("## Official sample set\n\nNot found at `dataset/sample_output.csv` - skipped.")
    with tempfile.TemporaryDirectory() as tmp:
        gold = build(tmp)
        ag = Agent(tmp, config, False)
        pred = ag.run(read_csv(os.path.join(tmp, "deletion_requests.csv")))
        m = score(pred, gold)
        summary["custom_cases"] = {k: v for k, v in m.items() if k != "failures"}
        sections.append("## Team-created cases (`evaluation/synthetic.py`)\n\n"
                        "Seven hand-built cases in the REAL dataset schema with independently hand-derived expected answers: "
                        "non-deletion export request, a full INCOMPLETE plan (remaining profile, search hit, identifiable "
                        "analytics profile, PII support ticket, active connector, restorable backup), COMPLETE via a "
                        "historical email (404 profile, anonymized analytics, redacted ticket, disabled flow, blocked "
                        "backup, retained audit record), a negated request, a tombstone still holding PII, a hash-only "
                        "record in a SQL inventory dump, and a post-audit evidence-capture that must be ignored.\n\n" + _fmt(m))
        if m["failures"]:
            sections.append("```json\n" + json.dumps(m["failures"], indent=1) + "\n```")
    report = ["# Evaluation report", "",
              "Generated by `python code/main.py --eval`. Metrics are defined in `evaluation/metrics.py`.", ""]
    notes = os.path.join(out_dir, "notes.md")
    report += sections
    if os.path.exists(notes):
        report += ["", open(notes, encoding="utf-8").read()]
    with open(os.path.join(out_dir, "evaluation_report.md"), "w", encoding="utf-8") as fh:
        fh.write("\n\n".join(report) + "\n")
    with open(os.path.join(out_dir, "metrics.json"), "w") as fh:
        json.dump(summary, fh, indent=1)
    print("\n\n".join(sections))
    return summary
